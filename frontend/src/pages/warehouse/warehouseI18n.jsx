const WarehouseI18nContext = createContext(null);

function interpolate(template, vars = {}) {
  return String(template || "").replace(/\{\{(\w+)\}\}/g, (_, key) =>
    vars[key] != null ? String(vars[key]) : ""
  );
}

function readLanguage() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === "en" || stored === "zh") return stored;
  } catch {
    /* ignore */
  }
  return "en";
}

export function WarehouseI18nProvider({ children }) {
  const [language, setLanguageState] = useState(readLanguage);

  const setLanguage = useCallback((next) => {
    if (next !== "en" && next !== "zh") return;
    setLanguageState(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback(
    (key, vars) => {
      const table = translations[language] || translations.en;
      const value = table[key] ?? translations.en[key] ?? key;
      return vars ? interpolate(value, vars) : value;
    },
    [language]
  );

  const value = useMemo(
    () => ({ language, setLanguage, t }),
    [language, setLanguage, t]
  );

  return (
    <WarehouseI18nContext.Provider value={value}>
      {children}
    </WarehouseI18nContext.Provider>
  );
}

export function useWarehouseI18n() {
  const ctx = useContext(WarehouseI18nContext);
  if (!ctx) {
    throw new Error("useWarehouseI18n must be used inside WarehouseI18nProvider");
  }
  return ctx;
}
